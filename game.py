"""Логика «Магического шара».

Модуль намеренно не импортирует Streamlit: его можно тестировать
и переиспользовать (CLI, бот, тесты) без веб-фреймворка.
"""

from __future__ import annotations

import random

#: Классические 20 ответов шара (в вольном переводе).
ANSWERS: tuple[str, ...] = (
    "Бесспорно да",
    "Определённо да",
    "Без сомнений",
    "Да, если действовать сейчас",
    "Скорее да, чем нет",
    "Пока не ясно — спроси снова",
    "Не могу сказать прямо сейчас",
    "Сконцентрируйся и спроси ещё раз",
    "Скорее нет, чем да",
    "Не рассчитывай на это",
    "Весьма сомнительно",
    "Перспективы туманны",
    "Мой ответ — нет",
    "Определённо нет",
    "Звёзды говорят «да»",
    "Всё в твоих руках",
    "Ответ придёт во сне",
    "Шар устал, попробуй позже",
    "Абсолютно точно",
    "Даже не думай",
)


def is_valid_question(question: str | None) -> bool:
    """True, если вопрос не пустой (пробелы не считаются)."""
    return bool(question and question.strip())


def pick_answer(
    question: str = "",
    *,
    previous: str | None = None,
    rng: random.Random | None = None,
) -> str:
    """Вернуть ответ шара.

    ``previous`` исключается из выбора, чтобы шар не повторялся дважды подряд.
    ``rng`` позволяет получить воспроизводимый результат в тестах.
    Сам ``question`` на ответ не влияет — это и есть магия.
    """
    source = rng or random
    pool = [a for a in ANSWERS if a != previous] or list(ANSWERS)
    return source.choice(pool)
